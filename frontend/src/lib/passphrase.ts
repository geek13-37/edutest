export interface PassphraseOptions {
  words: number; // 3..6
  separator: string; // "-" | "." | "_"
  includeNumber: boolean; // добавить двузначное число в конце
  capitalize: boolean; // Каждое слово с большой буквы
}

export const DEFAULT_PASSPHRASE_OPTS: PassphraseOptions = {
  words: 3,
  separator: "-",
  includeNumber: true,
  capitalize: false,
};

/** Равномерное [0, max) на crypto.getRandomValues, без modulo-смещения. */
function randInt(max: number): number {
  const limit = Math.floor(0xffffffff / max) * max;
  const buf = new Uint32Array(1);
  let x: number;
  do {
    crypto.getRandomValues(buf);
    x = buf[0];
  } while (x >= limit);
  return x % max;
}

export function generatePassphrase(o: PassphraseOptions = DEFAULT_PASSPHRASE_OPTS): string {
  const used = new Set<string>();
  const parts: string[] = [];
  while (parts.length < o.words && used.size < WORDS.length) {
    const w = WORDS[randInt(WORDS.length)];
    if (used.has(w)) continue;
    used.add(w);
    parts.push(o.capitalize ? w[0].toUpperCase() + w.slice(1) : w);
  }
  let phrase = parts.join(o.separator);
  if (o.includeNumber) phrase += o.separator + String(10 + randInt(90));
  return phrase;
}

/** Приблизительная энтропия фразы в битах. */
export function passphraseBits(o: PassphraseOptions): number {
  return o.words * Math.log2(WORDS.length) + (o.includeNumber ? Math.log2(90) : 0);
}

export function strengthLabel(bits: number): { label: string; tone: "warning" | "info" | "success" } {
  if (bits >= 40) return { label: "надежный", tone: "success" };
  if (bits >= 30) return { label: "хороший", tone: "info" };
  return { label: "средний", tone: "warning" };
}
