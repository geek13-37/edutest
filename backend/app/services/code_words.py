"""Короткие слова для кодов регистрации школ: <слово><4 цифры>, напр. сокол4821."""
import secrets

WORDS = [
    "СОКОЛ", "ОРБИТА", "КОМЕТА", "ФАКЕЛ", "ГРАНИТ", "ЯКОРЬ", "МАЯК", "ПАРУС",
    "КЕДР", "ФЕНИКС", "АТЛАС", "ВЕКТОР", "КОМПАС", "КРИСТАЛЛ", "МЕРИДИАН", "НЕПТУН",
    "ОКЕАН", "ПОЛЮС", "РАКЕТА", "САТУРН", "ТИТАН", "УРАГАН", "ФОРВАРД", "ХОЛМ",
    "ЦИКЛОН", "ЭВЕРЕСТ", "ЯНТАРЬ", "БАРС", "ВОЛНА", "ГЕЙЗЕР", "ДЕЛЬТА", "ЗЕНИТ",
    "ИСКРА", "КАСКАД", "ЛАВИНА", "МОЛНИЯ", "НАДИР", "ОАЗИС", "ПИК", "РИФ",
]


def generate_signup_code() -> str:
    word = secrets.choice(WORDS)
    digits = "".join(str(secrets.randbelow(10)) for _ in range(4))
    return f"{word}{digits}".lower()
